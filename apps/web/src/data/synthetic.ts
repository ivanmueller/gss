export const SYNTHETIC_COMMODITIES = ['Flaxseed', 'Canola', 'Yellow peas', 'Durum wheat'] as const;

const GRADES: Record<(typeof SYNTHETIC_COMMODITIES)[number], string> = {
  Flaxseed: 'No. 1 CW',
  Canola: 'No. 1 Canada',
  'Yellow peas': 'No. 2 CAN',
  'Durum wheat': 'No. 1 CWAD',
};

function quote(
  fields: Pick<Quote, 'id' | 'side' | 'deliveryBasis' | 'status' | 'quotedAt' | 'validUntil'> & {
    commodity: (typeof SYNTHETIC_COMMODITIES)[number];
    amount: string;
    currency: Quote['price']['currency'];
    window: [string, string];
    quantity: [string, string];
  },
): Quote {
  return {
    id: fields.id,
    side: fields.side,
    commodity: fields.commodity,
    grade: GRADES[fields.commodity],
    price: { amount: fields.amount, currency: fields.currency, unit: 'MT' },
    deliveryBasis: fields.deliveryBasis,
    status: fields.status,
    source: 'Manual entry',
    revision: 1,
    quotedAt: fields.quotedAt,
    validUntil: fields.validUntil,
    deliveryWindow: { start: fields.window[0], end: fields.window[1] },
    quantityMt: { min: fields.quantity[0], max: fields.quantity[1] },
  };
}

