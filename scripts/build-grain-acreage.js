// Builds apps/web/src/data/grains/acreage.ts: the acres insured in 2025 in Alberta,
// Saskatchewan and Manitoba by grain, class and variety, from the Canadian Grain Commission's
// "Grain varieties by acreage insured" (owner's request, 2026-11-05: the Grains window shows
// the classes and varieties most grown on the Prairies). Download the two 2025 CSV files from
// https://www.grainscanada.gc.ca/en/grain-research/statistics/varieties-by-acreage/
// (cereal-varieties/varieties-2025-c-en.csv and
// oilseed-pulse-minor-varieties/varieties-2025-g-en.csv), then run:
//
//   node scripts/build-grain-acreage.js varieties-2025-c-en.csv varieties-2025-g-en.csv
//
// British Columbia's rows are left out. Acres are summed over the three provinces per variety;
// the 12 most grown varieties of each grain and class are kept, with the class's total.
import { readFileSync, writeFileSync } from 'node:fs';

const PROVINCES = new Set(['Alberta', 'Saskatchewan', 'Manitoba']);
const KEEP = 12;

/** The CSV's grain names as the reference's grain ids. */
const GRAIN = {
  Wheat: 'wheat',
  'Amber Durum': 'wheat',
  Barley: 'barley',
  Oat: 'oats',
  Rye: 'rye',
  Triticale: 'triticale',
  Canola: 'canola',
  Lentil: 'lentils',
  Peas: 'peas',
  Soybeans: 'soybeans',
  Corn: 'corn',
  'Chick Peas': 'chickpeas',
  Flaxseed: 'flaxseed',
  'Mustard Seed': 'mustard',
  Canaryseed: 'canary-seed',
  Beans: 'beans',
  'Pea Beans': 'beans',
  Sunflower: 'sunflower',
  'Faba bean': 'faba-beans',
  Buckwheat: 'buckwheat',
};

/** One CSV line's cells; a quoted cell may hold commas, and "" is a quote. */
function cells(line) {
  const out = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (char === '"') quoted = false;
      else cell += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') {
      out.push(cell);
      cell = '';
    } else cell += char;
  }
  out.push(cell);
  return out;
}

function parse(file) {
  const [header = '', ...lines] = readFileSync(file, 'utf8').trim().split(/\r?\n/);
  const names = cells(header);
  return lines.map((line) => {
    const row = cells(line);
    return Object.fromEntries(names.map((name, index) => [name, (row[index] ?? '').trim()]));
  });
}

const [cereals, others] = process.argv.slice(2);
if (!cereals || !others) {
  console.error('Usage: node scripts/build-grain-acreage.js <cereals.csv> <oilseeds-pulses.csv>');
  process.exit(1);
}

/** grain → class (the CSV's own, or the grain's name when it gives none) → variety → acres */
const totals = {};
for (const row of [...parse(cereals), ...parse(others)]) {
  if (!PROVINCES.has(row.province)) continue;
  const grain = GRAIN[row.grain_code];
  if (!grain) throw new Error(`Unknown grain in the CSV: ${row.grain_code}`);
  // Pea beans are a class of beans of their own; the others give their class, or none.
  const kind =
    row.grain_code === 'Pea Beans' ? 'PEA BEANS' : row.cgc_class || row.grain_code.toUpperCase();
  const acres = Number(row.acres);
  if (!Number.isFinite(acres)) throw new Error(`Acres not a number: ${row.acres}`);
  totals[grain] ??= {};
  totals[grain][kind] ??= {};
  totals[grain][kind][row.variety] = (totals[grain][kind][row.variety] ?? 0) + acres;
}

const grains = {};
for (const [grain, kinds] of Object.entries(totals).sort()) {
  grains[grain] = {};
  for (const [kind, varieties] of Object.entries(kinds).sort()) {
    const ranked = Object.entries(varieties).sort((a, b) => b[1] - a[1]);
    grains[grain][kind] = {
      acres: Math.round(ranked.reduce((sum, [, acres]) => sum + acres, 0)),
      // "NOT SPECIFIED" counts in the class's acres but is no variety.
      varieties: ranked
        .filter(([name]) => name !== 'NOT SPECIFIED')
        .slice(0, KEEP)
        .map(([name, acres]) => [name, Math.round(acres)]),
    };
  }
}

const out = `// Generated by scripts/build-grain-acreage.js from the Canadian Grain Commission's "Grain
// varieties by acreage insured" for 2025 (Alberta, Saskatchewan and Manitoba summed; British
// Columbia left out). Do not edit by hand: run the script again with newer files.

/** grain id → class as the CSV names it → its acres and its most grown varieties (as printed). */
export const ACREAGE: Record<
  string,
  Record<string, { acres: number; varieties: [string, number][] }>
> = ${JSON.stringify(grains, null, 2)};
`;
writeFileSync(new URL('../apps/web/src/data/grains/acreage.ts', import.meta.url), out);
console.log(`Wrote ${String(Object.keys(grains).length)} grains.`);
